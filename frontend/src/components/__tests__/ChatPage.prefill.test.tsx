/**
 * Tests URL-param prefill behavior added in the lab-result-interpretation feature.
 * ChatPage reads `?prefill=...` on mount, sets draft message, then clears params.
 */
import { cleanup } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  renderWithProviders,
  screen,
} from "../../test-utils/renderWithProviders";
import ChatPage from "../ChatPage";

const mockSetDraftMessage = vi.fn();
const mockUseChat = vi.fn();
const mockUsePatientContext = vi.fn();

vi.mock("../../hooks/useChat", () => ({
  useChat: () => mockUseChat(),
}));

vi.mock("../../contexts/PatientContext", () => ({
  usePatientContext: () => mockUsePatientContext(),
  usePatients: () => ({ patients: [], isLoading: false }),
}));

// ChatPage renders DevIdentityBanner in DEV mode which pulls extra contexts.
// Force non-DEV so we get the simpler patient-selector path.
vi.stubEnv("DEV", false);

function defaultChatReturn() {
  return {
    messages: [],
    chatId: undefined,
    isLoading: false,
    error: null,
    sendMessage: vi.fn(),
    clearChat: vi.fn(),
    draftMessage: "",
    setDraftMessage: mockSetDraftMessage,
  };
}

describe("ChatPage URL-param prefill", () => {
  afterEach(() => {
    cleanup();
    vi.clearAllMocks();
  });

  beforeEach(() => {
    mockUsePatientContext.mockReturnValue({
      currentPatientId: "pat-001",
      setCurrentPatientId: vi.fn(),
    });
    mockUseChat.mockReturnValue(defaultChatReturn());
  });

  it("calls setDraftMessage with the prefill param on mount", () => {
    renderWithProviders(<ChatPage />, {
      router: { initialEntries: ["/patient/chat?prefill=Hello%20there&sourceDoc=doc-abc"] },
    });
    expect(mockSetDraftMessage).toHaveBeenCalledWith("Hello there");
  });

  it("does not call setDraftMessage when prefill param is absent", () => {
    renderWithProviders(<ChatPage />, {
      router: { initialEntries: ["/patient/chat"] },
    });
    expect(mockSetDraftMessage).not.toHaveBeenCalled();
  });

  it("renders the prefill value in the chat input when draftMessage is set", () => {
    mockUseChat.mockReturnValue({
      ...defaultChatReturn(),
      draftMessage: "Please interpret my lab results.",
    });
    renderWithProviders(<ChatPage />, {
      router: { initialEntries: ["/patient/chat"] },
    });
    const input = screen.getByPlaceholderText(/ask about/i) as HTMLInputElement;
    expect(input.value).toBe("Please interpret my lab results.");
  });

  it("prefill message stays under 200 characters when generated by DocumentsPage", () => {
    const docName = "CBC + Metabolic Panel — Full Blood Work";
    const prefill = `Please interpret my lab results from "${docName}".`;
    expect(prefill.length).toBeLessThanOrEqual(200);
  });
});
